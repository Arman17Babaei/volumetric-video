#!/usr/bin/env python3

# run_p4_experiment.py

import subprocess

from mininet.log import setLogLevel, info

from common import (
    endpoint_tuning,
    add_access_delays,
    run_trial,
)
from linux_bottleneck import DELAY_MS_ONEWAY
from p4_bottleneck import build_p4_net
from p4utils.utils.helper import load_topo


def program_p4_switch(net_api, h1, h2, table_only=False):
    """
    Program the BMv2 switch using the *actual* host IPs/MACs.

    - MyIngress.ipv4_lpm: dst IP -> (dst MAC, port)
    - MyEgress.aqm: PI2 params for egress port 2
    """
    topo = load_topo('topology.json')  # generated by p4-utils on start
    thrift_port = topo.get_thrift_port('s1')

    h1_ip = h1.IP()
    h2_ip = h2.IP()
    h1_mac = h1.MAC()
    h2_mac = h2.MAC()

    print(f">>> [P4] Programming switch on Thrift port {thrift_port}")
    print(f"    h1: IP={h1_ip}, MAC={h1_mac}, port=1")
    print(f"    h2: IP={h2_ip}, MAC={h2_mac}, port=2")

    cli_cmds = f"""
table_clear MyIngress.ipv4_lpm
table_add MyIngress.ipv4_lpm MyIngress.ipv4_forward {h1_ip}/32 => {h1_mac} 1
table_add MyIngress.ipv4_lpm MyIngress.ipv4_forward {h2_ip}/32 => {h2_mac} 2

table_clear MyEgress.aqm
table_add MyEgress.aqm MyEgress.pi2 2 => 1342 13421 20000 15
"""

    # Run simple_switch_CLI and feed the commands via stdin
    result = subprocess.run(
        ["simple_switch_CLI", "--thrift-port", str(thrift_port)],
        input=cli_cmds,
        text=True,
        capture_output=True,
    )

    if result.returncode != 0:
        print(">>> [P4] ERROR programming switch:")
        print(result.stderr)
        raise RuntimeError("Failed to program P4 switch with simple_switch_CLI")

    # Optional: show the CLI output for debugging
    if result.stdout.strip():
        print(">>> [P4] simple_switch_CLI output:")
        print(result.stdout)


def main():
    setLogLevel('info')

    print(">>> [P4] Building P4/BMv2 network with aqm.p4")
    net_api, mn, h1, h2, s1 = build_p4_net(p4src="aqm.p4")

    try:
        # 1) Program the P4 switch tables based on real IP/MACs
        program_p4_switch(net_api, h1, h2)

        # 2) Host-side tuning and delays (same as Linux experiment)
        print(">>> [P4] Endpoint tuning on h1/h2 (ECN + Prague + fq)")
        endpoint_tuning(h1)
        endpoint_tuning(h2)

        print(f">>> [P4] Adding access delays: {DELAY_MS_ONEWAY} ms one-way at hosts")
        add_access_delays(h1, h2, DELAY_MS_ONEWAY)

        # 3) Static ARP so hosts know each other's MAC (using real MACs)
        h1_ip = h1.IP()
        h2_ip = h2.IP()
        h1_mac = h1.MAC()
        h2_mac = h2.MAC()

        print(">>> [P4] Installing static ARP entries")
        h1.cmd(f"arp -s {h2_ip} {h2_mac} || true")
        h2.cmd(f"arp -s {h1_ip} {h1_mac} || true")

        # 4) Sanity ping
        print(">>> [P4] Sanity ping over P4/PI2 dataplane")
        ping_out = h1.cmd(f"ping -c 3 {h2_ip}")
        info(ping_out)

        # 5) Full iperf+ping trial
        print(">>> [P4] Starting iperf+ping trial under P4 PI2 bottleneck")
        run_trial(
            h1,
            h2,
            bottleneck_node=None,
            bottleneck_dev="",
            mode_name="p4_pi2",
            parallel=4,
            seconds=20,
        )

        print(">>> [P4] Trial complete. Logs:")
        print("      /tmp/ping_p4_pi2.log  (latency trace)")
        print("      /tmp/iperf_server.log (throughput)")

        input(">>> [P4] Press Enter to stop the P4 network...")

    finally:
        print(">>> [P4] Stopping P4 network")
        mn.stop()


if __name__ == "__main__":
    main()
